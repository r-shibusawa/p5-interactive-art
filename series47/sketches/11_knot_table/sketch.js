// 空間全体をねじる（軸のまわりに、軸方向の位置で決まる角度だけ回す）＝ 結び目の型は変わらない
function twistAll(c, ax, cen, al, sg) {
  let m = Math.hypot(...ax); ax = ax.map((x) => x / m);
  return c.map((p) => {
    let v = [p[0] - cen[0], p[1] - cen[1], p[2] - cen[2]], h = v[0] * ax[0] + v[1] * ax[1] + v[2] * ax[2], th = al * Math.exp(-(h * h) / (sg * sg));
    let cs = Math.cos(th), sn = Math.sin(th), kv = [ax[1] * v[2] - ax[2] * v[1], ax[2] * v[0] - ax[0] * v[2], ax[0] * v[1] - ax[1] * v[0]];
    return [0, 1, 2].map((d) => cen[d] + v[d] * cs + kv[d] * sn + ax[d] * h * (1 - cs));
  });
}

function newProblem() {
  for (let attempt = 0; attempt < 60; attempt++) {
    let name = CAND[Math.floor(Math.random() * CAND.length)], c = knotCurves(name, 300)[0];
    for (let k = 0; k < 3; k++) c = twistAll(c, [Math.random() - 0.5, Math.random() - 0.5, Math.random() - 0.5], [(Math.random() - 0.5), (Math.random() - 0.5), (Math.random() - 0.5)], (Math.random() < 0.5 ? -1 : 1) * twistAmp * (0.5 + Math.random()), 0.5 + Math.random() * 0.5);
    let v = rotPts([c], Math.random() * 6, Math.random() * 6), d = diagramOf(v);
    let K = knotByName(name).pd;
    if (d.pd.length > maxCross || d.pd.length < K.length + 2) continue;           // 元より 2 つ以上多く、多すぎない図
    let id = identify(d.pd);
    if (!id.hits.some((h) => h.name === name)) continue;                          // 念のため（点が粗すぎた図は捨てる）
    answer = name; cs = v; D = d; inv = id; shown = 0; guess = '';
    return;
  }
  answer = '3_1'; cs = rotPts(knotCurves('3_1'), 0.4, 0.3); D = diagramOf(cs); inv = identify(D.pd); shown = 0; guess = '';   // うまく作れなかったとき
}

