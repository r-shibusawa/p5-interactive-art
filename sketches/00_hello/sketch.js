// setup() … 最初に1回だけ実行される
function setup() {
  createCanvas(600, 400); // 幅600 × 高さ400 のキャンバスをつくる
}

// draw() … 1秒間に約60回、ずっとくり返し実行される
function draw() {
  background(30); // 背景を塗りつぶす（0=黒 〜 255=白）

  noStroke(); // 線（ふち）を描かない
  fill(255, 100, 150); // 塗りの色（赤, 緑, 青）それぞれ 0〜255
  circle(mouseX, mouseY, 50); // マウスの位置に、直径50の円
}

