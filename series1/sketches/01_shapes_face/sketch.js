// ============================================
// 01 図形と色でキャラクターをつくる
// 目がマウスを追いかけるロボット
// ============================================
// 座標： 左上が (0, 0)。右に行くほど x が大きく、下に行くほど y が大きい

function setup() {
  createCanvas(600, 400);
}

function draw() {
  background(250, 240, 220); // クリーム色の背景

  // ---- 地面 ----
  noStroke();
  fill(120, 200, 140);
  rect(0, 330, 600, 70); // rect(x, y, 幅, 高さ)

  // ---- アンテナ ----
  stroke(60);
  strokeWeight(6);
  line(300, 100, 300, 50); // line(x1, y1, x2, y2)
  noStroke();
  fill(255, 80, 80);
  circle(300, 45, 24);

  // ---- 顔 ----
  stroke(60);
  strokeWeight(6);
  fill(255, 210, 90);
  rect(190, 100, 220, 200, 40); // 最後の 40 は角の丸み

  // ---- 白目 ----
  fill(255);
  circle(250, 180, 70);
  circle(350, 180, 70);

  // ---- 黒目（マウスのほうを向く）----
  // map(値, 元の最小, 元の最大, 新しい最小, 新しい最大)
  let dx = map(mouseX, 0, width, -15, 15);
  let dy = map(mouseY, 0, height, -15, 15);
  noStroke();
  fill(40);
  circle(250 + dx, 180 + dy, 30);
  circle(350 + dx, 180 + dy, 30);

  // ---- 口（マウスを押すと開く）----
  stroke(60);
  strokeWeight(6);
  if (mouseIsPressed) {
    fill(200, 60, 80);
    ellipse(300, 255, 80, 50); // ellipse(x, y, 幅, 高さ)
  } else {
    noFill();
    arc(300, 240, 80, 40, 0, PI); // 半円のにっこり口
  }

  // ---- ほっぺ ----
  noStroke();
  fill(255, 150, 150, 150); // 4つ目の数字は透明度
  circle(215, 240, 30);
  circle(385, 240, 30);
}

